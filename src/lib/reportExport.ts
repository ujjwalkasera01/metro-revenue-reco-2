import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { downloadFile, toCsv } from './format';

export interface ReportRow { code: string; name: string; line: string; expected: number; reported: number; adjustments: number; variance: number; status: string }
export interface ReportMeta { id: string; periodLabel: string; status: string; auditRef: string; signatory: string; signatoryTitle: string; approvedAt?: string; generatedBy: string }

const r = (n: number) => 'Rs ' + Math.round(n).toLocaleString('en-IN');

export function reportCsv(meta: ReportMeta, rows: ReportRow[]) {
  const csv = toCsv([
    ['Report', meta.id], ['Period', meta.periodLabel], ['Audit reference', meta.auditRef], ['Status', meta.status], [],
    ['Code', 'Station', 'Line', 'Expected (AFC)', 'Reported (Station)', 'Adjustments', 'Net variance', 'Balance type', 'Status'],
    ...rows.map((x) => [x.code, x.name, x.line, x.expected, x.reported, x.adjustments, x.variance, x.variance < 0 ? 'Receivable' : x.variance > 0 ? 'Payable' : 'Nil', x.status]),
  ]);
  downloadFile(`${meta.id}.csv`, csv, 'text/csv');
}

export async function reportPdf(meta: ReportMeta, rows: ReportRow[]) {
  const doc = await PDFDocument.create();
  const page = doc.addPage([595, 842]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const navy = rgb(0.08, 0.18, 0.42);
  let y = 800;
  const t = (s: string, x: number, size = 9, f = font, color = rgb(0.1, 0.1, 0.15)) => page.drawText(s, { x, y, size, font: f, color });
  page.drawRectangle({ x: 0, y: 770, width: 595, height: 72, color: navy });
  y = 812; t('MetroRev - Final Revenue Reconciliation & Settlement Report', 40, 13, bold, rgb(1, 1, 1));
  y = 792; t(`${meta.id}  |  Period: ${meta.periodLabel}  |  Audit ref: ${meta.auditRef}`, 40, 9, font, rgb(0.85, 0.9, 1));
  y = 745; t(`Status: ${meta.status}    Generated by: ${meta.generatedBy}    SIMULATED DEMO DATA`, 40, 9, bold);
  y = 715;
  const cols = [40, 80, 200, 290, 375, 455];
  ['Code', 'Station', 'Expected', 'Reported', 'Adjustments', 'Variance'].forEach((h, i) => t(h, cols[i], 9, bold, navy));
  y -= 6; page.drawLine({ start: { x: 40, y }, end: { x: 555, y }, thickness: 0.5, color: navy });
  y -= 14;
  let te = 0, tr = 0, ta = 0, tv = 0;
  for (const x of rows) {
    [x.code, x.name, r(x.expected), r(x.reported), r(x.adjustments), r(x.variance)].forEach((v, i) => t(v, cols[i]));
    te += x.expected; tr += x.reported; ta += x.adjustments; tv += x.variance;
    y -= 16;
  }
  page.drawLine({ start: { x: 40, y: y + 10 }, end: { x: 555, y: y + 10 }, thickness: 0.5 });
  ['', 'TOTAL', r(te), r(tr), r(ta), r(tv)].forEach((v, i) => t(v, cols[i], 9, bold));
  y -= 30;
  t(`Final ${tv < 0 ? 'receivable from stations' : 'payable to stations'}: ${r(Math.abs(tv))}`, 40, 11, bold, navy);
  y = 180;
  t('Authorised signatory', 40, 9, bold);
  page.drawRectangle({ x: 40, y: 110, width: 200, height: 55, borderColor: rgb(0.6, 0.6, 0.7), borderWidth: 0.6 });
  y = 135; t(meta.status === 'Approved' ? `Digitally signed (simulated) - ${meta.signatory}` : 'Signature pending', 50, 8);
  y = 95; t(`${meta.signatory}, ${meta.signatoryTitle}`, 40, 9);
  y = 80; t(meta.approvedAt ? `Approved on ${new Date(meta.approvedAt).toLocaleString('en-IN')}` : 'Awaiting approval', 40, 8);
  y = 40; t('This document was generated from a frontend prototype using sample data and has no legal or financial validity.', 40, 7, font, rgb(0.5, 0.5, 0.55));
  const bytes = await doc.save();
  downloadFile(`${meta.id}.pdf`, bytes.slice().buffer as ArrayBuffer, 'application/pdf');
}
